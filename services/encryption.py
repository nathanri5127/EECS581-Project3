import os
from decimal import Decimal

from cryptography.fernet import Fernet, InvalidToken
from sqlalchemy import LargeBinary
from sqlalchemy.types import TypeDecorator

# Helper for Fernet encryption
def _fernet():
    key = os.getenv("FERNET_KEY")
    if not key:
        raise RuntimeError(
            "FERNET_KEY must be configured before encrypted data can be used"
        )
    try:
        return Fernet(key.encode("ascii"))
    except (ValueError, TypeError):
        raise RuntimeError("FERNET_KEY is not a valid Fernet key") from None

# Encrypt a value
def encrypt_value(value):
    if value is None:
        return None
    return _fernet().encrypt(str(value).encode("utf-8"))

# Decrypt a value
def decrypt_value(value):
    if value is None:
        return None
    try:
        return _fernet().decrypt(bytes(value)).decode("utf-8")
    except InvalidToken:
        raise RuntimeError(
            "Encrypted data could not be decrypted; check FERNET_KEY"
        ) from None

